const MARKETING: Partial<Record<Lang, Dict>> = { en: EN, fr: FR, no: NO };

/** Traducteur de la page d'accueil, repli explicite sur l'anglais. */
export function makeTM(lang: Lang) {
  return (key: string): string => {
    const path = key.split(".");
    const pick = (obj: Dict | undefined) =>
      path.reduce<unknown>((o, k) => (o && typeof o === "object" ? (o as Dict)[k] : undefined), obj);
    const direct = pick(MARKETING[lang]);
    const v = direct ?? pick(EN);
    if (typeof direct !== "string") {
      signalerManque("pages", `marketing.${key}`, lang, typeof v === "string" ? "repli_fr" : "absente");
    }
    return typeof v === "string" ? v : key;
  };
}

export type TM = ReturnType<typeof makeTM>;
